void *apply_pointer_relocations(TRelDataFile *file, RelFileTrailer *relocs) {
    u32 i;
    u32 n = relocs->reloc_count;
    u16 *offsets = (u16 *)(relocs + 1);
    u32 *p = (u32 *)file->data;

    for (i = 0; i < n; i++) {
        p += *offsets++;
        *p += (uaddr)file->data;
    }
    file->root = (void *)(relocs->root_offset + (uaddr)file->data);
    return file->root;
}

void *apply_rel_relocations(TRelDataFile *file) {
    u16 *offsets;
    u8 *cur;
    RelFileTrailer *trailer;
    u8 *data;

    data = file->data;
    trailer = (RelFileTrailer *)(data + file->size) - 1;
    offsets = (u16 *)(trailer->reloc_offset + (uaddr)data);
    cur = data;
    u32 n = trailer->reloc_count;
    u32 i;
    for (i = 0; i < n; i++) {
        cur += *offsets++ * 4;
        *(u32 *)cur += (uaddr)file->data;
    }
    file->root = (void *)(trailer->root_offset + (uaddr)file->data);
    return file->root;
}

