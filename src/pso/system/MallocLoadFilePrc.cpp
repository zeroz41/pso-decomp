u32 decrypt_quest_data(void *src, s32 size, void *dst, u32 capacity) {
    QuestDownloadFile *file = (QuestDownloadFile *)src;
    u32 decompressed_size;
    u32 seed;

    decompressed_size = file->decompressed_size;
    seed = file->seed;
    bswap_32(&decompressed_size);
    bswap_32(&seed);
    if (decompressed_size > capacity) {
        return 0U;
    }
    SubtractiveRng rng;
    rng.set_seed(seed);
    rng.crypt_data_be((u32 *)file->data, size - 8);
    prs_decompress_buffer(file->data, dst);
    return decompressed_size;
}

u32 QuestDownloadFile::decrypt(s32 size, void *dst, u32 capacity) {
    u32 v0 = decompressed_size;
    s32 v4 = seed;

    if (v0 > capacity) {
        return 0U;
    }
    SubtractiveRng rng;
    rng.set_seed(v4);
    rng.xor_buffer((u32 *)data, size - 8);
    prs_decompress_buffer(data, dst);
    return v0;
}

void *QuestDownloadFile::alloc_download_quest(s32 size, s32 *out_size) {
    s32 v0 = decompressed_size;
    s32 v4 = seed;
    void *ret;

    ret = alloc(v0);
    if (ret == NULL) {
        return NULL;
    }
    SubtractiveRng rng;
    rng.set_seed(v4);
    rng.xor_buffer((u32 *)data, size - 8);
    prs_decompress_buffer(data, ret);
    if (out_size != NULL) {
        *out_size = v0;
    }
    return ret;
}


void *load_encrypted_text_archive(char *name, s32 *out_size) {
    s32 size;
    s32 h;
    QuestDownloadFile *buf;
    void *ret;
    s32 archive_size;

    size = get_resource_file_size(name);
    if (size <= 0) {
        return NULL;
    }
    if ((size <= 0x40000) && (tmp_buf_is_free() != 0)) {
        buf = (QuestDownloadFile *)tmp_buf_use_req(load_file_prc_buffer_tag);
        read_disc_file(name, buf);
        ret = buf->alloc_download_quest(size, &archive_size);
        tmp_buf_release(load_file_prc_buffer_tag);
    } else {
        TGStream st(name, 1);
        buf = (QuestDownloadFile *)alloc(0x800);
        st.read_sectors_sync(1, buf);
        archive_size = buf->decompressed_size;
        h = buf->seed;
        safe_free(buf);
        ret = alloc(archive_size);
        buf = (QuestDownloadFile *)load_disc_file(name);
        SubtractiveRng rng;
        rng.set_seed(h);
        rng.xor_buffer((u32 *)buf->data, size - 8);
        prs_decompress_buffer(buf->data, ret);
        safe_free(buf);
    }
    if (out_size != NULL) {
        *out_size = archive_size;
    }
    return ret;
}

